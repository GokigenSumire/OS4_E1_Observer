    public static int code(String name){for(int i=0;i<NAMES.length;i++)if(NAMES[i].equals(name))return BASE+i;return 0;}
    public static boolean valid(int code){return code>=BASE&&code<BASE+NAMES.length;}
    public static String label(int code){return valid(code)?NAMES[code-BASE]:"NATIVE_UNKNOWN";}
    public static int count(){return NAMES.length;}
    public static String eventName(int action){return switch(action){case 0->"NATIVE_EVENT_DOWN";case 1->"NATIVE_EVENT_UP";case 2->"NATIVE_EVENT_MOVE";case 3->"NATIVE_EVENT_CANCEL";case 5->"NATIVE_EVENT_POINTER_DOWN";case 6->"NATIVE_EVENT_POINTER_UP";default->"NATIVE_EVENT_OTHER";};}
    public static boolean isEditResult(int code){return code==code("NATIVE_EDIT_BASELINE_UNAVAILABLE")||code==code("NATIVE_EDIT_RESULTS_UNAVAILABLE")||code==code("NATIVE_EDIT_RESULTS_TRUNCATED")||code>=code("NATIVE_AUTH_WAITING")&&code<=code("NATIVE_EDITOR_RESULT_UNKNOWN")||code>=code("NATIVE_AUTH_UNLOCK_PENDING")&&code<=code("NATIVE_NAV_UNCHANGED");}
    public static int editCause(int cause){return cause>=1&&cause<=18?code(new String[]{"NATIVE_AUTH_WAITING","NATIVE_AUTH_SUCCEEDED","NATIVE_AUTH_CANCELLED","NATIVE_AUTH_ERROR","NATIVE_AUTH_ABORTED","NATIVE_EDITOR_OPENED","NATIVE_EDITOR_SAVE_REQUESTED","NATIVE_EDITOR_SAVED","NATIVE_EDITOR_SAVE_REJECTED","NATIVE_EDITOR_CANCEL_REQUESTED","NATIVE_EDITOR_CLOSED","NATIVE_EDITOR_RESULT_UNKNOWN","NATIVE_AUTH_UNLOCK_PENDING","NATIVE_AUTH_UNLOCK_TIMEOUT","NATIVE_AUTH_ENTRY_DESTROYED","NATIVE_NAV_NEXT_PRESENTED","NATIVE_NAV_PREVIOUS_PRESENTED","NATIVE_NAV_UNCHANGED"}[cause-1]):0;}
    public static int commandResult(String status){
        if(status==null)return code("NATIVE_HOST_CALLBACK_INVALID");
        return code(switch(status){case "COMMITTED"->"NATIVE_HOST_COMMITTED";case "FAILED"->"NATIVE_HOST_FAILED";case "STALE_TICKET"->"NATIVE_HOST_STALE_TICKET";case "CANCELLED"->"NATIVE_HOST_CANCELLED";case "EXPIRED"->"NATIVE_HOST_EXPIRED";case "NO_ENGINE"->"NATIVE_HOST_NO_ENGINE";case "TARGET_NOT_LOCK"->"NATIVE_HOST_TARGET_NOT_LOCK";case "BUSY_EDIT"->"NATIVE_HOST_BUSY_EDIT";case "UNKNOWN_STATE"->"NATIVE_HOST_UNKNOWN_STATE";default->"NATIVE_HOST_CALLBACK_INVALID";});
    }
    public static boolean isRelayResult(int code){return isEditResult(code)||code>=code("NATIVE_HOST_COMMITTED")&&code<=code("NATIVE_HOST_CALLBACK_INVALID");}
    public static String rawEventName(String source,int action){
        if(source==null||!java.util.Set.of("ROOT","PANEL","INTERCEPT","TOUCH_HANDLER","INJECTOR").contains(source))return "NATIVE_EVENT_OTHER";
        String suffix=switch(action){case 0->"DOWN";case 1->"UP";case 2->"MOVE";case 3->"CANCEL";case 5->"POINTER_DOWN";case 6->"POINTER_UP";default->"OTHER";};
        return "NATIVE_RAW_"+source+"_"+suffix;
    }
